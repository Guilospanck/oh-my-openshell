//! Per-gateway operations: the config, service and registration steps for a gateway of any kind,
#![allow(dead_code)] // wired in by the planner and the wizard (Tasks 4 and 7)
//! as `Step`s (nothing here touches the host; `setup::execute` does).
use crate::assets;
use crate::gateway::{self, chain, cmd, script, step, Paths, WAIT_SCRIPT};
use crate::gwmodel::{GatewaySpec, GwKind, Registry};
use crate::platform::{Facts, Host, Os, PkgMgr, Runtime};
use crate::setup::{Step, StepKind};
use std::path::{Path, PathBuf};

/// Step ids are `&'static str`; a plan is built once per run, so leaking the few dozen short
/// per-gateway ids is the simplest way to give each gateway's steps distinct ones.
fn sid(spec: &GatewaySpec, role: &str) -> &'static str {
    Box::leak(format!("gw-{}-{role}", spec.kind.driver()).into_boxed_str())
}

fn st(spec: &GatewaySpec, role: &str, title: &str, kind: StepKind) -> Step {
    let mut s = step(sid(spec, role), title, kind);
    s.id = sid(spec, role);
    s
}

/// The osh data dir's generated config for a gateway.
pub fn config_path(p: &Paths, name: &str) -> PathBuf {
    p.data.join("gateways").join(format!("{name}.toml"))
}

pub fn unit_name(name: &str) -> String {
    format!("osh-gateway-{name}.service")
}

fn unit_path(p: &Paths, name: &str) -> PathBuf {
    let config = p.config_home.parent().unwrap_or(&p.home);
    config.join("systemd/user").join(unit_name(name))
}

pub fn agent_label(name: &str) -> String {
    format!("dev.guilospanck.{name}")
}

pub fn agent_plist_path(p: &Paths, name: &str) -> PathBuf {
    p.home
        .join("Library/LaunchAgents")
        .join(format!("{}.plist", agent_label(name)))
}

/// The main gateway keeps the packaged service's database; extras get their own.
pub fn db_dir(p: &Paths, spec: &GatewaySpec) -> PathBuf {
    if spec.main {
        p.state.join("gateway")
    } else {
        p.state.join(format!("gateway-{}", spec.kind.driver()))
    }
}

/// The TLS material the main gateway's service writes, shared by every gateway.
pub fn tls_dir(p: &Paths, os: Os) -> PathBuf {
    match os {
        Os::Linux => p.state.join("tls"),
        Os::MacOs => p.state.join("homebrew/tls"),
    }
}

/// A gateway config for `spec`. The main keeps the packaged service's default ports; an extra
/// binds its own.
pub fn gateway_toml(spec: &GatewaySpec, os: Os) -> String {
    let d = spec.kind.driver();
    let mut t = format!(
        "# Generated by osh for the gateway {name}. Edit freely: osh keeps your changes.\n\
         [openshell]\nversion = 2\n\n[openshell.gateway]\nname = \"{name}\"\n",
        name = spec.name
    );
    if !spec.main {
        t.push_str(&format!(
            "bind_address = \"127.0.0.1:{}\"\nhealth_bind_address = \"127.0.0.1:{}\"\nmetrics_bind_address = \"127.0.0.1:{}\"\n",
            spec.port,
            spec.health_port(),
            spec.metrics_port()
        ));
    }
    t.push_str(&format!(
        "compute_driver = \"{d}\"\n\n[openshell.drivers.{d}]\n"
    ));
    if spec.kind == GwKind::Docker && os == Os::MacOs {
        // Containers in the Colima VM reach the host loopback through this name, which is in the
        // shared server certificate's SANs.
        t.push_str(&format!(
            "grpc_endpoint = \"https://host.docker.internal:{}\"\n",
            spec.port
        ));
    }
    t.push_str(&format!(
        "# Lets sandboxes bind-mount host folders via --driver-config-json mounts.\n\
         allow_driver_config = true\nenable_bind_mounts = true\n\n\
         [openshell.drivers.{d}.resource_admission]\nenabled = false\n"
    ));
    t
}

/// The Linux user unit for an extra gateway, shaped like the packaged `openshell-gateway.service`.
pub fn systemd_unit(spec: &GatewaySpec, exe: &Path) -> String {
    format!(
        "[Unit]\nDescription=OpenShell Gateway ({name})\nAfter=default.target\n\n\
         [Service]\nType=simple\n\
         Environment=OPENSHELL_LOCAL_TLS_DIR=%h/.local/state/openshell/tls\n\
         EnvironmentFile=-%E/openshell/gateway.env\n\
         ExecStart={exe} gateway-service {name}\n\
         Restart=on-failure\nRestartSec=5s\nUMask=0077\n\n\
         [Install]\nWantedBy=default.target\n",
        name = spec.name,
        exe = exe.display()
    )
}

/// The macOS launchd agent for a gateway osh runs itself.
pub fn launchd_plist(spec: &GatewaySpec, exe: &Path, logs: &Path) -> String {
    let esc = |p: &Path| {
        p.display()
            .to_string()
            .replace('&', "&amp;")
            .replace('<', "&lt;")
            .replace('>', "&gt;")
    };
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key><array><string>{exe}</string><string>gateway-service</string><string>{name}</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>StandardOutPath</key><string>{logs}/gateway.out.log</string>
  <key>StandardErrorPath</key><string>{logs}/gateway.err.log</string>
</dict></plist>
"#,
        label = agent_label(&spec.name),
        name = spec.name,
        exe = esc(exe),
        logs = esc(logs)
    )
}

pub fn registry_write_step(reg: &Registry, p: &Paths) -> Step {
    step(
        "gw-registry",
        "Remember this gateway",
        StepKind::Write {
            path: p.data.join("gateways.json"),
            content: reg.to_json(),
        },
    )
}

/// Registers an extra gateway with the CLI without changing which gateway is selected.
/// $1 = config dir, $2 = name, $3 = port, $4 = the gateway whose certificates to share.
const REGISTER_EXTRA: &str = r#"set -e
dst="$1/gateways/$2"
mkdir -p "$dst"
[ -d "$dst/mtls" ] || cp -R "$1/gateways/$4/mtls" "$dst/"
previous="$(cat "$1/active_gateway" 2>/dev/null || echo "$4")"
if ! openshell gateway list -o json | grep -q "\"$2\""; then
  openshell gateway add "https://localhost:$3" --local --name "$2"
  openshell gateway select "$previous"
fi"#;

/// Replaces the installer's `openshell` registration with the main gateway's own name.
/// $1 = config dir, $2 = name.
const REGISTER_MAIN: &str = r#"set -e
dst="$1/gateways/$2"
mkdir -p "$dst"
[ -d "$dst/mtls" ] || cp -R "$1/gateways/openshell/mtls" "$dst/"
if ! openshell gateway list -o json | grep -q "\"$2\""; then
  openshell gateway add https://127.0.0.1:17670 --local --name "$2"
fi
openshell gateway select "$2"
if openshell gateway list -o json | grep -q '"openshell"'; then openshell gateway remove openshell; fi"#;

/// Config (written once), service, registration and wait for a gateway osh runs as its own service.
fn own_service_steps(
    f: &Facts,
    p: &Paths,
    h: &dyn Host,
    spec: &GatewaySpec,
    register: Option<StepKind>,
    mut steps: Vec<Step>,
) -> Vec<Step> {
    let cfg = config_path(p, &spec.name);
    if h.read(&cfg).is_none() {
        steps.push(st(
            spec,
            "config",
            &format!("Write the {} gateway config", spec.kind.label()),
            StepKind::Write {
                path: cfg,
                content: gateway_toml(spec, f.os),
            },
        ));
    }
    match f.os {
        Os::Linux => {
            steps.push(st(
                spec,
                "unit",
                "Write the gateway's systemd user unit",
                StepKind::Write {
                    path: unit_path(p, &spec.name),
                    content: systemd_unit(spec, &p.exe),
                },
            ));
            steps.push(st(
                spec,
                "reload",
                "Reload systemd user units",
                cmd("systemctl", &["--user", "daemon-reload"]),
            ));
            steps.push(st(
                spec,
                "enable",
                &format!("Start the {} gateway", spec.kind.label()),
                cmd(
                    "systemctl",
                    &["--user", "enable", "--now", &unit_name(&spec.name)],
                ),
            ));
        }
        Os::MacOs => {
            let logs = db_dir(p, spec);
            if spec.kind == GwKind::Docker && h.read(&p.config_home.join("gateway.env")).is_none() {
                steps.push(st(
                    spec,
                    "env",
                    "Write gateway.env (Colima Docker socket)",
                    StepKind::Write {
                        path: p.config_home.join("gateway.env"),
                        content: assets::embedded("gateway.env").unwrap_or_default().into(),
                    },
                ));
            }
            let plist = agent_plist_path(p, &spec.name);
            steps.push(st(
                spec,
                "agent",
                "Write the launchd agent",
                StepKind::Write {
                    path: plist.clone(),
                    content: launchd_plist(spec, &p.exe, &logs),
                },
            ));
            steps.push(st(
                spec,
                "logs",
                "Create the log directory",
                cmd("mkdir", &["-p", &logs.to_string_lossy()]),
            ));
            steps.push(st(
                spec,
                "bootout",
                "Stop a running agent",
                script(
                    r#"launchctl bootout "gui/$(id -u)/$1" 2>/dev/null || true"#,
                    &[&agent_label(&spec.name)],
                ),
            ));
            steps.push(st(
                spec,
                "enable",
                &format!("Start the {} gateway", spec.kind.label()),
                script(
                    r#"launchctl bootstrap "gui/$(id -u)" "$1""#,
                    &[&plist.to_string_lossy()],
                ),
            ));
        }
    }
    if let Some(r) = register {
        steps.push(st(
            spec,
            "register",
            "Register the gateway with the OpenShell CLI",
            r,
        ));
    }
    steps.push(st(
        spec,
        "wait",
        "Wait for the gateway to answer",
        script(WAIT_SCRIPT, &[&spec.name]),
    ));
    chain(steps, None)
}

/// Adds an extra gateway: its own config, service and CLI registration, then the registry entry.
/// Certificates are shared with the main gateway (or the legacy `openshell`).
pub fn add_gateway_steps(
    f: &Facts,
    p: &Paths,
    h: &dyn Host,
    reg: &Registry,
    spec: &GatewaySpec,
) -> Vec<Step> {
    let certs = reg
        .main()
        .map_or("openshell", |m| m.name.as_str())
        .to_string();
    let register = script(
        REGISTER_EXTRA,
        &[
            &p.config_home.to_string_lossy(),
            &spec.name,
            &spec.port.to_string(),
            &certs,
        ],
    );
    let mut steps = own_service_steps(f, p, h, spec, Some(register), Vec::new());
    let mut after = reg.clone();
    after.add(spec.clone());
    let mut w = registry_write_step(&after, p);
    w.after = steps.last().map(|s| s.id);
    steps.push(w);
    steps
}

/// Sets up the main gateway. On Linux and for the VM type it is the OpenShell-provided service
/// with `gateway.toml` rewritten for this kind; on macOS a Docker or Podman main runs as its own
/// launchd agent (the Homebrew service does not inherit Colima's `DOCKER_HOST`).
/// `installing`: this run installed OpenShell, so the installer's `openshell` registration is
/// replaced by the main's own name.
pub fn main_gateway_steps(
    f: &Facts,
    p: &Paths,
    h: &dyn Host,
    spec: &GatewaySpec,
    installing: bool,
) -> Vec<Step> {
    let register = installing.then(|| {
        script(
            REGISTER_MAIN,
            &[&p.config_home.to_string_lossy(), &spec.name],
        )
    });
    let mut after = Registry::default();
    after.add(spec.clone());
    let mut steps = if f.os == Os::MacOs && spec.kind != GwKind::Vm {
        let stop = st(
            spec,
            "stop-brew",
            "Stop the Homebrew gateway service",
            cmd("brew", &["services", "stop", "openshell"]),
        );
        own_service_steps(f, p, h, spec, register, vec![stop])
    } else {
        let target = p.config_home.join("gateway.toml");
        let wanted = gateway_toml(spec, f.os);
        let installed = h.read(&target);
        let current = installed.as_deref() == Some(wanted.as_str());
        if !installing && current && gateway::service_running(f.os, h) {
            return Vec::new();
        }
        let mut steps = Vec::new();
        if !current {
            if let Some(old) = installed.filter(|t| !t.is_empty()) {
                steps.push(st(
                    spec,
                    "backup",
                    "Keep a copy of your gateway.toml before replacing it",
                    StepKind::Write {
                        path: p.config_home.join("gateway.toml.osh-bak"),
                        content: old,
                    },
                ));
            }
            steps.push(st(
                spec,
                "config",
                &format!("Install the {} gateway config", spec.kind.label()),
                StepKind::Write {
                    path: target,
                    content: wanted,
                },
            ));
        }
        match f.os {
            Os::MacOs if f.pkg == PkgMgr::Brew => steps.push(st(
                spec,
                "restart",
                "Restart the OpenShell gateway service",
                cmd("brew", &["services", "restart", "openshell"]),
            )),
            Os::MacOs => steps.push(st(
                spec,
                "restart",
                "Restart the OpenShell gateway service",
                StepKind::Manual("brew services restart openshell".into()),
            )),
            Os::Linux => {
                steps.push(st(
                    spec,
                    "reload",
                    "Reload systemd user units",
                    cmd("systemctl", &["--user", "daemon-reload"]),
                ));
                steps.push(st(
                    spec,
                    "enable",
                    "Enable the gateway service",
                    cmd("systemctl", &["--user", "enable", "openshell-gateway"]),
                ));
                steps.push(st(
                    spec,
                    "restart",
                    "Restart the OpenShell gateway service",
                    cmd("systemctl", &["--user", "restart", "openshell-gateway"]),
                ));
            }
        }
        if let Some(r) = register {
            steps.push(st(
                spec,
                "register",
                "Register the gateway with the OpenShell CLI",
                r,
            ));
        }
        steps.push(st(
            spec,
            "wait",
            "Wait for the gateway to answer",
            script(WAIT_SCRIPT, &[&spec.name]),
        ));
        chain(steps, None)
    };
    let mut w = registry_write_step(&after, p);
    w.after = steps.last().map(|s| s.id);
    steps.push(w);
    steps
}

/// Removes a gateway osh created: stops its service, unregisters it, forgets it. The database stays
/// unless `delete_data`. The main cannot go while extras exist; gateways osh did not create are
/// refused.
pub fn remove_gateway_steps(
    f: &Facts,
    p: &Paths,
    reg: &Registry,
    name: &str,
    delete_data: bool,
) -> Result<Vec<Step>, String> {
    let spec = reg
        .get(name)
        .ok_or_else(|| format!("{name} is not managed by osh, so osh will not remove it"))?
        .clone();
    if spec.main {
        let extras: Vec<&str> = reg
            .gateways
            .iter()
            .filter(|g| !g.main)
            .map(|g| g.name.as_str())
            .collect();
        if !extras.is_empty() {
            return Err(format!(
                "{name} is the main gateway; remove {} first",
                extras.join(", ")
            ));
        }
    }
    let mut steps = Vec::new();
    let packaged = spec.main && !(f.os == Os::MacOs && spec.kind != GwKind::Vm);
    match (f.os, packaged) {
        (Os::Linux, true) => steps.push(st(
            &spec,
            "stop",
            "Stop and disable the gateway service",
            script(
                "systemctl --user disable --now openshell-gateway 2>/dev/null || true",
                &[],
            ),
        )),
        (Os::Linux, false) => {
            steps.push(st(
                &spec,
                "stop",
                "Stop and disable the gateway service",
                script(
                    "systemctl --user disable --now \"$1\" 2>/dev/null || true",
                    &[&unit_name(&spec.name)],
                ),
            ));
            steps.push(st(
                &spec,
                "unit",
                "Remove its systemd unit",
                cmd("rm", &["-f", &unit_path(p, &spec.name).to_string_lossy()]),
            ));
            steps.push(st(
                &spec,
                "reload",
                "Reload systemd user units",
                cmd("systemctl", &["--user", "daemon-reload"]),
            ));
        }
        (Os::MacOs, true) => steps.push(st(
            &spec,
            "stop",
            "Stop the Homebrew gateway service",
            script("brew services stop openshell 2>/dev/null || true", &[]),
        )),
        (Os::MacOs, false) => {
            steps.push(st(
                &spec,
                "stop",
                "Stop the launchd agent",
                script(
                    r#"launchctl bootout "gui/$(id -u)/$1" 2>/dev/null || true"#,
                    &[&agent_label(&spec.name)],
                ),
            ));
            steps.push(st(
                &spec,
                "unit",
                "Remove the launchd agent",
                cmd(
                    "rm",
                    &["-f", &agent_plist_path(p, &spec.name).to_string_lossy()],
                ),
            ));
        }
    }
    steps.push(st(
        &spec,
        "unregister",
        "Unregister the gateway from the OpenShell CLI",
        script(
            "openshell gateway remove \"$1\" 2>/dev/null || true",
            &[&spec.name],
        ),
    ));
    steps.push(st(
        &spec,
        "rmconfig",
        "Remove its generated config",
        cmd("rm", &["-f", &config_path(p, &spec.name).to_string_lossy()]),
    ));
    if delete_data {
        steps.push(st(
            &spec,
            "rmdata",
            "Delete its data",
            cmd("rm", &["-rf", &db_dir(p, &spec).to_string_lossy()]),
        ));
    }
    let mut after = reg.clone();
    after.remove(name);
    steps.push(registry_write_step(&after, p));
    Ok(chain(steps, None))
}

/// Wipes a gateway osh created and starts it again empty, with its own service, database and
/// runtime.
pub fn reset_steps_for(f: &Facts, p: &Paths, spec: &GatewaySpec, rt: Option<Runtime>) -> Vec<Step> {
    let state = p.state.to_string_lossy().into_owned();
    let config = p.config_home.to_string_lossy().into_owned();
    let packaged = spec.main && !(f.os == Os::MacOs && spec.kind != GwKind::Vm);
    let (stop, start) = match (f.os, packaged) {
        (Os::Linux, true) => (
            cmd("systemctl", &["--user", "stop", "openshell-gateway"]),
            cmd("systemctl", &["--user", "start", "openshell-gateway"]),
        ),
        (Os::Linux, false) => (
            cmd("systemctl", &["--user", "stop", &unit_name(&spec.name)]),
            cmd("systemctl", &["--user", "start", &unit_name(&spec.name)]),
        ),
        (Os::MacOs, true) => (
            cmd("brew", &["services", "stop", "openshell"]),
            cmd("brew", &["services", "start", "openshell"]),
        ),
        (Os::MacOs, false) => (
            script(
                r#"launchctl bootout "gui/$(id -u)/$1" 2>/dev/null || true"#,
                &[&agent_label(&spec.name)],
            ),
            script(
                r#"launchctl bootstrap "gui/$(id -u)" "$1""#,
                &[&agent_plist_path(p, &spec.name).to_string_lossy()],
            ),
        ),
    };
    let sweep = if spec.kind == GwKind::Vm {
        script(gateway::SWEEP_VMS_SCRIPT, &[&state])
    } else {
        let bin = rt
            .filter(|r| r.bin() == spec.kind.driver())
            .map_or(spec.kind.driver(), |r| r.bin());
        script(
            gateway::SWEEP_CONTAINERS_SCRIPT,
            &[
                bin,
                &state,
                &config,
                if f.os == Os::MacOs { "darwin" } else { "linux" },
            ],
        )
    };
    let db = |ext: &str| {
        db_dir(p, spec)
            .join(format!("openshell.db{ext}"))
            .to_string_lossy()
            .into_owned()
    };
    chain(
        vec![
            st(
                spec,
                "reset-sandboxes",
                "Delete the sandboxes through the gateway",
                script(gateway::DELETE_SANDBOXES_SCRIPT, &[&spec.name]),
            ),
            st(spec, "reset-stop", "Stop the gateway", stop),
            st(spec, "reset-settle", "Let it settle", cmd("sleep", &["2"])),
            st(
                spec,
                "reset-sweep",
                "Remove leftover sandbox runtimes",
                sweep,
            ),
            st(
                spec,
                "reset-db",
                "Delete the database",
                cmd("rm", &["-f", &db(""), &db("-shm"), &db("-wal")]),
            ),
            st(spec, "reset-start", "Start the gateway", start),
            st(
                spec,
                "reset-wait",
                "Wait for the gateway to answer",
                script(WAIT_SCRIPT, &[&spec.name]),
            ),
        ],
        None,
    )
}

/// `osh gateway-service <name>`: runs one osh-managed gateway in the foreground with the shared
/// TLS material and its own database. Returns only when `exec` fails.
pub fn service_exec(name: &str, p: &Paths) -> std::io::Error {
    use std::os::unix::process::CommandExt;
    let reg = Registry::load(&p.data);
    let os = if cfg!(target_os = "macos") {
        Os::MacOs
    } else {
        Os::Linux
    };
    let Some(spec) = reg.get(name).cloned() else {
        return std::io::Error::other(format!("{name} is not in osh's gateway registry"));
    };
    let home = p.home.to_string_lossy().into_owned();
    let mut c = std::process::Command::new(gateway::gateway_binary());
    c.arg("--config").arg(config_path(p, name));
    if let Ok(t) = std::fs::read_to_string(p.config_home.join("gateway.env")) {
        for (k, v) in gateway::parse_env_file(&t, &home) {
            c.env(k, v);
        }
    }
    let dir = db_dir(p, &spec);
    let _ = std::fs::create_dir_all(&dir);
    if std::env::var_os("OPENSHELL_LOCAL_TLS_DIR").is_none() {
        c.env("OPENSHELL_LOCAL_TLS_DIR", tls_dir(p, os));
    }
    c.env(
        "OPENSHELL_DB_URL",
        format!("sqlite:{}?mode=rwc", dir.join("openshell.db").display()),
    );
    c.exec()
}

